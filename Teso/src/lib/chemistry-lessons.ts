/** Groups lessons by unit */
export function groupByUnit(lessons: LessonData[]): Map<number, LessonData[]> {
  const map = new Map<number, LessonData[]>();
  for (const l of lessons) {
    if (!map.has(l.unit)) map.set(l.unit, []);
    map.get(l.unit)!.push(l);
  }
  return map;
}
